"""Turn an exported microduck MLP policy (ONNX) back into an rsl_rl actor state dict.

The ONNX graph of scripts/export.py is (obs - mean) / (std + eps), then
Gemm, Elu, Gemm, Elu, Gemm, Elu, Gemm. Its initializers are named after the
actor state dict (obs_normalizer._mean, mlp.0.weight, ...), except the
divisor, which is std + eps. This script reads them back, sets the
normalizer count high so the running statistics stay put during a
continuation, sets the action noise std, and checks that the rebuilt actor
reproduces the ONNX output.

    uv run scripts/onnx_to_checkpoint.py roller.onnx logs/rsl_rl/roller_dance/roller_onnx_init/actor.pt --std 0.25

The output holds actor_state_dict, iter 0 and infos with the source path and
SHA256. It has no critic and no optimizer state. scripts/finetune_roller_dance.py
loads it with --init.
"""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path

import numpy as np
import torch

NORMALIZER_EPS = 1e-2  # rsl_rl EmpiricalNormalization default
NORMALIZER_COUNT = 1_000_000_000
LINEAR = ("mlp.0", "mlp.2", "mlp.4", "mlp.6")


def sha256(path: Path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def read_onnx(path: Path) -> tuple[dict[str, np.ndarray], dict[str, str]]:
    import onnx
    from onnx import numpy_helper

    model = onnx.load(str(path))
    inits = {i.name: numpy_helper.to_array(i) for i in model.graph.initializer}
    meta = {p.key: p.value for p in model.metadata_props}
    # The divisor feeds the Div node; its initializer has an autogenerated name.
    div = [n for n in model.graph.node if n.op_type == "Div"]
    if len(div) != 1:
        raise ValueError(f"expected one Div node, found {len(div)}")
    inits["__divisor__"] = inits[div[0].input[1]]
    return inits, meta


def actor_state_dict(inits: dict[str, np.ndarray], std: float, eps: float = NORMALIZER_EPS,
                     count: int = NORMALIZER_COUNT) -> dict[str, torch.Tensor]:
    mean = torch.as_tensor(np.array(inits["obs_normalizer._mean"]), dtype=torch.float32).reshape(1, -1)
    div = torch.as_tensor(np.array(inits["__divisor__"]), dtype=torch.float32).reshape(1, -1)
    obs_std = (div - eps).clamp(min=0.0)
    out_dim = inits["mlp.6.weight"].shape[0]
    sd = {
        "obs_normalizer._mean": mean,
        "obs_normalizer._var": obs_std * obs_std,
        "obs_normalizer._std": obs_std,
        "obs_normalizer.count": torch.tensor(count, dtype=torch.long),
        "distribution.std_param": torch.full((out_dim,), float(std)),
    }
    for layer in LINEAR:
        sd[f"{layer}.weight"] = torch.as_tensor(np.array(inits[f"{layer}.weight"]), dtype=torch.float32)
        sd[f"{layer}.bias"] = torch.as_tensor(np.array(inits[f"{layer}.bias"]), dtype=torch.float32)
    return sd


def mlp_forward(sd: dict[str, torch.Tensor], obs: torch.Tensor, eps: float = NORMALIZER_EPS) -> torch.Tensor:
    """The actor mean in plain torch, for the parity check."""
    x = (obs - sd["obs_normalizer._mean"]) / (sd["obs_normalizer._std"] + eps)
    for i, layer in enumerate(LINEAR):
        x = x @ sd[f"{layer}.weight"].T + sd[f"{layer}.bias"]
        if i < len(LINEAR) - 1:
            x = torch.nn.functional.elu(x)
    return x


def onnx_forward(path: Path, obs: np.ndarray) -> np.ndarray:
    import onnxruntime as ort

    sess = ort.InferenceSession(str(path), providers=["CPUExecutionProvider"])
    name = sess.get_inputs()[0].name
    return np.concatenate([sess.run(None, {name: row[None].astype(np.float32)})[0] for row in obs])


def parity(path: Path, sd: dict[str, torch.Tensor], n: int = 64, seed: int = 0) -> float:
    """Max |actor - onnx| on random obs drawn around the normalizer statistics."""
    g = np.random.default_rng(seed)
    mean = sd["obs_normalizer._mean"].numpy()[0]
    scale = sd["obs_normalizer._std"].numpy()[0] + NORMALIZER_EPS
    obs = (mean + scale * g.standard_normal((n, mean.shape[0]))).astype(np.float32)
    ref = onnx_forward(path, obs)
    got = mlp_forward(sd, torch.as_tensor(obs)).numpy()
    return float(np.max(np.abs(ref - got)))


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("onnx", type=Path)
    p.add_argument("out", type=Path)
    p.add_argument("--std", type=float, default=0.25, help="initial action noise std")
    p.add_argument("--source-url", default="")
    a = p.parse_args()
    inits, meta = read_onnx(a.onnx)
    sd = actor_state_dict(inits, a.std)
    err = parity(a.onnx, sd)
    print(f"PARITY max abs diff {err:.3e}", flush=True)
    if err > 1e-4:
        raise SystemExit(f"rebuilt actor differs from {a.onnx} by {err}")
    a.out.parent.mkdir(parents=True, exist_ok=True)
    torch.save({"actor_state_dict": sd, "iter": 0,
                "infos": {"source": str(a.onnx), "source_url": a.source_url, "source_sha256": sha256(a.onnx),
                          "onnx_metadata": meta, "action_noise_std": a.std}}, a.out)
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
